export function getText(keyPath: string, lang: Language): string {
  const parts = keyPath.split('.');
  let curr: any = t;
  for (const part of parts) {
    if (curr && curr[part] !== undefined) {
      curr = curr[part];
    } else {
      return keyPath;
    }
  }
  if (typeof curr === 'object' && curr !== null) {
    return curr[lang] || curr['en'] || keyPath;
  }
  return String(curr);
}
